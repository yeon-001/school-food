@st.cache_data(ttl=3600)
def get_meal_data(
    office_code,
    school_code,
    start_date,
    end_date
):
    """
    선택한 학교의 지정 기간 점심 급식 데이터를 가져온다.
    """

    params = {
        "Type": "json",

        "pIndex": 1,

        "pSize": 1000,

        "ATPT_OFCDC_SC_CODE": office_code,

        "SD_SCHUL_CODE": school_code,

        # 2 = 중식
        "MMEAL_SC_CODE": "2",

        "MLSV_FROM_YMD": start_date.strftime(
            "%Y%m%d"
        ),

        "MLSV_TO_YMD": end_date.strftime(
            "%Y%m%d"
        )
    }

    # 인증키가 있으면 사용
    if NEIS_KEY:

        params["KEY"] = NEIS_KEY

    try:

        response = requests.get(
            MEAL_API,
            params=params,
            timeout=30
        )

        response.raise_for_status()

        data = response.json()

        # 급식 정보가 없는 경우
        if "mealServiceDietInfo" not in data:

            return []

        # row 데이터 찾기
        for item in data["mealServiceDietInfo"]:

            if "row" in item:

                return item["row"]

        return []

    except Exception:

        return []


# =========================================================
# 메뉴 이름 정리
# =========================================================

def clean_menu_name(menu):
    """
    급식 메뉴에서 알레르기 번호와 불필요한 표시를 제거한다.

    예:

    미역국5.6.13.
    → 미역국

    김치찌개5.6.9.
    → 김치찌개
    """

    menu = str(menu)

    # -----------------------------------------------------
    # HTML 줄바꿈 태그 제거
    # -----------------------------------------------------

    menu = re.sub(
        r"<br\s*/?>",
        " ",
        menu,
        flags=re.IGNORECASE
    )

    # -----------------------------------------------------
    # 괄호 안 내용 제거
    # -----------------------------------------------------

    menu = re.sub(
        r"\([^)]*\)",
        "",
        menu
    )

    # -----------------------------------------------------
    # 대괄호 안 내용 제거
    # -----------------------------------------------------

    menu = re.sub(
        r"\[[^\]]*\]",
        "",
        menu
    )

    # -----------------------------------------------------
    # 알레르기 번호 제거
    #
    # 예:
    # 5.6.13.
    # 5.6.9
    # -----------------------------------------------------

    menu = re.sub(
        r"(?:\d+\.)+\s*$",
        "",
        menu
    )

    menu = re.sub(
        r"(?:\d+\s*)+$",
        "",
        menu
    )

    # -----------------------------------------------------
    # 앞뒤 공백 및 기호 제거
    # -----------------------------------------------------

    menu = menu.strip()

    menu = menu.strip(
        " *·"
    )

    # -----------------------------------------------------
    # 여러 공백을 하나로 정리
    # -----------------------------------------------------

    menu = re.sub(
        r"\s+",
        " ",
        menu
    )

    return menu.strip()


# =========================================================
# 국 종류인지 확인
# =========================================================

def is_soup(menu):
    """
    메뉴가 국, 찌개, 탕, 전골 등의 종류인지 확인한다.
    """

    menu = clean_menu_name(
        menu
    )

    if not menu:

        return False

    # -----------------------------------------------------
    # 이름 끝부분으로 국 종류 확인
    # -----------------------------------------------------

    soup_endings = [
        "국",
        "찌개",
        "탕",
        "전골"
    ]

    for ending in soup_endings:

        if menu.endswith(ending):

            return True

    # -----------------------------------------------------
    # 특별히 국 종류로 처리할 메뉴
    # -----------------------------------------------------

    soup_names = [

        "육개장",
        "닭개장",

        "감자탕",
        "갈비탕",
        "곰탕",
        "설렁탕",
        "삼계탕",
        "추어탕",
        "도가니탕",

        "순대국",
        "순댓국"
    ]

    if menu in soup_names:

        return True

    return False


# =========================================================
# 국 종류 분석
# =========================================================

def analyze_soups(meal_rows):
    """
    급식 데이터에서 국 종류를 찾아
    각각 몇 번 등장했는지 계산한다.
    """

    soup_list = []

    # -----------------------------------------------------
    # 급식 데이터 하나씩 확인
    # -----------------------------------------------------

    for row in meal_rows:

        # -------------------------------------------------
        # 점심 데이터만 사용
        # -------------------------------------------------

        meal_code = str(
            row.get(
                "MMEAL_SC_CODE",
                "2"
            )
        )

        if meal_code != "2":

            continue

        # -------------------------------------------------
        # 급식 메뉴 가져오기
        # -------------------------------------------------

        menu_text = row.get(
            "DDISH_NM",
            ""
        )

        if not menu_text:

            continue

        # -------------------------------------------------
        # <br> 기준으로 메뉴를 나눈다.
        # -------------------------------------------------

        menus = re.split(
            r"<br\s*/?>",
            menu_text,
            flags=re.IGNORECASE
        )

        # -------------------------------------------------
        # 각각의 메뉴 확인
        # -------------------------------------------------

        for menu in menus:

            menu = clean_menu_name(
                menu
            )

            if not menu:

                continue

            # -------------------------------------------------
            # 국 종류인지 확인
            # -------------------------------------------------

            if is_soup(menu):

                soup_list.append(
                    menu
                )

    # -----------------------------------------------------
    # 국 종류가 하나도 없는 경우
    # -----------------------------------------------------

    if not soup_list:

        return pd.DataFrame(
            columns=[
                "국 종류",
                "횟수"
            ]
        )

    # -----------------------------------------------------
    # 국 종류별 횟수 계산
    # -----------------------------------------------------

    count_series = pd.Series(
        soup_list
    ).value_counts()

    # -----------------------------------------------------
    # 데이터프레임으로 변환
    # -----------------------------------------------------

    result = pd.DataFrame({

        "국 종류": count_series.index,

        "횟수": count_series.values
    })

    return result


