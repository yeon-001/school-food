# =========================================================
# 학교 검색 함수
# =========================================================

def search_school(keyword):
    """
    학교 이름으로 NEIS 학교정보를 검색한다.
    """

    params = {
        "Type": "json",
        "pIndex": 1,
        "pSize": 100,
        "SCHUL_NM": keyword
    }

    # 인증키가 있으면 사용
    if NEIS_KEY:
        params["KEY"] = NEIS_KEY

    try:

        response = requests.get(
            SCHOOL_API,
            params=params,
            timeout=10
        )

        response.raise_for_status()

        data = response.json()

        # 학교 정보가 없는 경우
        if "schoolInfo" not in data:
            return []

        # row 데이터 찾기
        for item in data["schoolInfo"]:

            if "row" in item:
                return item["row"]

        return []

    except Exception:

        return []


# =========================================================
# 학교 이름 확장 검색
# =========================================================

def get_search_keywords(keyword):
    """
    사용자가 학교 이름을 짧게 입력해도
    학교를 찾을 수 있도록 검색어를 확장한다.
    """

    keywords = [keyword]

    # -----------------------------------------------------
    # 여고 → 여자고등학교
    # -----------------------------------------------------

    if "여고" in keyword:

        keywords.append(
            keyword.replace(
                "여고",
                "여자고등학교"
            )
        )

    # -----------------------------------------------------
    # 고 → 고등학교
    # -----------------------------------------------------

    if keyword.endswith("고"):

        keywords.append(
            keyword[:-1] + "고등학교"
        )

    # -----------------------------------------------------
    # 중 → 중학교
    # -----------------------------------------------------

    if keyword.endswith("중"):

        keywords.append(
            keyword[:-1] + "중학교"
        )

    # -----------------------------------------------------
    # 초 → 초등학교
    # -----------------------------------------------------

    if keyword.endswith("초"):

        keywords.append(
            keyword[:-1] + "초등학교"
        )

    # 중복 제거
    return list(dict.fromkeys(keywords))


# =========================================================
# 학교 검색 + 확장 검색
# =========================================================

def search_school_with_fallback(keyword):
    """
    먼저 입력한 학교 이름 그대로 검색하고,
    결과가 없으면 확장된 이름으로 검색한다.
    """

    all_results = []

    search_keywords = get_search_keywords(
        keyword
    )

    for word in search_keywords:

        results = search_school(
            word
        )

        for school in results:

            school_code = school.get(
                "SD_SCHUL_CODE"
            )

            # 이미 추가된 학교인지 확인
            already_exists = any(
                x.get("SD_SCHUL_CODE") == school_code
                for x in all_results
            )

            if not already_exists:

                all_results.append(
                    school
                )

        # 결과를 찾았으면 검색 종료
        if all_results:
            break

    return all_results


